#!/usr/bin/env python3
"""Gate: every Swift code block in the documentation compiles against the
public API, as an app would use it.

    scripts/check-doc-snippets.py

Collects the ```swift blocks of every DocC article (Sources/*/*.docc) and
the code blocks of every `///` doc comment, wraps each article or comment in
a function, and builds them as a separate package that depends on this one.
Blocks may use `system`, `entity` and `interface` without declaring them.
Blocks containing `.package(` (Package.swift excerpts) are skipped.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORK = ROOT / ".build" / "doc-snippets"
PARAMS = {"system": "GrentonSystem", "entity": "BoundEntity", "interface": "MobileInterfaceDTO"}
IMPORTS = ["Foundation", "GrentonModel", "GrentonRuntime", "GrentonProvisioning", "GrentonDevices"]


def article_groups():
    for path in sorted(ROOT.glob("Sources/*/*.docc/*.md")):
        blocks = re.findall(r"```swift\n(.*?)```", path.read_text(), re.S)
        yield str(path.relative_to(ROOT)), blocks


def comment_groups():
    for path in sorted(ROOT.glob("Sources/**/*.swift")):
        lines = path.read_text().split("\n")
        i = 0
        while i < len(lines):
            if lines[i].strip().startswith("///"):
                start = i
                text = []
                while i < len(lines) and lines[i].strip().startswith("///"):
                    text.append(re.sub(r"^\s*/// ?", "", lines[i]))
                    i += 1
                blocks = re.findall(r"```(?:swift)?\n(.*?)```", "\n".join(text) + "\n", re.S)
                if blocks:
                    yield f"{path.relative_to(ROOT)}:{start + 1}", blocks
            else:
                i += 1


def wrap(index, origin, blocks):
    blocks = [b for b in blocks if ".package(" not in b]
    if not blocks:
        return None
    body = "\n".join(l for b in blocks for l in b.split("\n") if not l.startswith("import "))
    declared = set(re.findall(r"\b(?:let|var)\s+(\w+)", body))
    params = ", ".join(f"{name}: {type_}" for name, type_ in PARAMS.items() if name not in declared)
    indented = "\n".join("    " + l for l in body.split("\n"))
    return f"// {origin}\nfunc snippet{index}({params}) async throws {{\n{indented}\n}}\n"


functions = []
for origin, blocks in list(article_groups()) + list(comment_groups()):
    code = wrap(len(functions), origin, blocks)
    if code:
        functions.append(code)

(WORK / "Sources" / "DocSnippets").mkdir(parents=True, exist_ok=True)
(WORK / "Package.swift").write_text(f"""// swift-tools-version: 6.0
// Generated by scripts/check-doc-snippets.py — do not edit.
import PackageDescription
let package = Package(
    name: "DocSnippets", platforms: [.macOS(.v13)],
    dependencies: [.package(path: "{ROOT}")],
    targets: [.target(name: "DocSnippets", dependencies: [
        .product(name: "GrentonProvisioning", package: "{ROOT.name}"),
        .product(name: "GrentonDevices", package: "{ROOT.name}"),
        .product(name: "GrentonRuntime", package: "{ROOT.name}"),
        .product(name: "GrentonModel", package: "{ROOT.name}"),
    ])]
)
""")
source = "\n".join(f"import {m}" for m in IMPORTS) + "\n\n" + "\n".join(functions)
(WORK / "Sources" / "DocSnippets" / "Snippets.swift").write_text(source)

result = subprocess.run(["swift", "build", "--package-path", str(WORK)], capture_output=True, text=True)
errors = [l for l in (result.stdout + result.stderr).split("\n") if "error:" in l]
for line in errors:
    print(line)
print(f"doc snippets: {len(functions)} group(s) from articles and doc comments, "
      f"{'OK' if result.returncode == 0 else 'FAILED'}")
if result.returncode != 0:
    print(f"(generated source: {WORK / 'Sources/DocSnippets/Snippets.swift'})")
sys.exit(result.returncode)
