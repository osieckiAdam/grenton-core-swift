#!/usr/bin/env python3
"""Gate: every Swift code block in the documentation compiles against the
public API, as an app would use it.

    scripts/check-doc-snippets.py

Collects the ```swift blocks of every DocC article (Sources/*/*.docc), the
`language-swift` blocks of the site pages (site/), and the code blocks of
every `///` doc comment, wraps each article or comment in
a function, and builds them as a separate package that depends on this one.
Each group is its own file with exactly the imports its blocks declare —
`import GrentonKit` when they declare none — so a snippet that shows one
import is proven to work with that import. Blocks may use `system`,
`entity` and `interface` without declaring them. Blocks containing
`.package(` or `.testTarget(` (Package.swift excerpts) are skipped.

The consumer scenarios in scripts/consumer/ are compiled in the same
package, unchanged: complete programs an app could contain, with their
own imports and no `@testable`.
"""
import html
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORK = ROOT / ".build" / "doc-snippets"
PARAMS = {"system": "GrentonSystem", "entity": "BoundEntity", "interface": "MobileInterfaceDTO"}
PRODUCTS = ["GrentonKit", "GrentonSimulation", "GrentonProvisioning", "GrentonDevices", "GrentonRuntime", "GrentonModel"]
CONSUMER = ROOT / "scripts" / "consumer"


def article_groups():
    for path in sorted(ROOT.glob("Sources/*/*.docc/*.md")):
        blocks = re.findall(r"```swift\n(.*?)```", path.read_text(), re.S)
        yield str(path.relative_to(ROOT)), blocks


def site_groups():
    for path in sorted(ROOT.glob("site/**/*.html")):
        blocks = re.findall(r'<code class="language-swift">(.*?)</code>', path.read_text(), re.S)
        yield str(path.relative_to(ROOT)), [html.unescape(re.sub(r"<[^>]+>", "", b)) for b in blocks]


def comment_groups():
    for path in sorted(ROOT.glob("Sources/**/*.swift")):
        lines = path.read_text().split("\n")
        i = 0
        while i < len(lines):
            if lines[i].strip().startswith("///"):
                start = i
                text = []
                while i < len(lines) and lines[i].strip().startswith("///"):
                    text.append(re.sub(r"^\s*/// ?", "", lines[i]))
                    i += 1
                blocks = re.findall(r"```(?:swift)?\n(.*?)```", "\n".join(text) + "\n", re.S)
                if blocks:
                    yield f"{path.relative_to(ROOT)}:{start + 1}", blocks
            else:
                i += 1


def wrap(index, origin, blocks):
    blocks = [b for b in blocks if ".package(" not in b and ".testTarget(" not in b]
    if not blocks:
        return None
    lines = [l for b in blocks for l in b.split("\n")]
    imports = sorted({l for l in lines if l.startswith("import ")} - {"import Foundation"})
    if not imports:
        imports = ["import GrentonKit"]
    body = "\n".join(l for l in lines if not l.startswith("import "))
    declared = set(re.findall(r"\b(?:let|var)\s+(\w+)", body))
    # Only the implicit names the blocks use, so a group with its own
    # narrower import is not handed types it never imported.
    params = ", ".join(f"{name}: {type_}" for name, type_ in PARAMS.items()
                       if name not in declared and re.search(rf"\b{name}\b", body))
    indented = "\n".join("    " + l for l in body.split("\n"))
    header = "\n".join(["import Foundation"] + imports)
    return f"// {origin}\n{header}\n\nfunc snippet{index}({params}) async throws {{\n{indented}\n}}\n"


functions = []
for origin, blocks in list(article_groups()) + list(site_groups()) + list(comment_groups()):
    code = wrap(len(functions), origin, blocks)
    if code:
        functions.append(code)

sources = WORK / "Sources" / "DocSnippets"
if sources.exists():
    for stale in sources.glob("*.swift"):
        stale.unlink()
sources.mkdir(parents=True, exist_ok=True)
products = "\n".join(f'        .product(name: "{p}", package: "{ROOT.name}"),' for p in PRODUCTS)
(WORK / "Package.swift").write_text(f"""// swift-tools-version: 6.2
// Generated by scripts/check-doc-snippets.py — do not edit.
import PackageDescription
let package = Package(
    name: "DocSnippets", platforms: [.macOS(.v13)],
    dependencies: [.package(path: "{ROOT}")],
    targets: [.target(name: "DocSnippets", dependencies: [
{products}
    ])]
)
""")
for index, code in enumerate(functions):
    (sources / f"Snippet{index}.swift").write_text(code)
scenarios = sorted(CONSUMER.glob("*.swift"))
for path in scenarios:
    (sources / f"Consumer_{path.name}").write_text(path.read_text())

result = subprocess.run(["swift", "build", "--package-path", str(WORK)], capture_output=True, text=True)
errors = [l for l in (result.stdout + result.stderr).split("\n") if "error:" in l]
for line in errors:
    print(line)
print(f"doc snippets: {len(functions)} group(s) from articles and doc comments, "
      f"{len(scenarios)} consumer scenario(s), "
      f"{'OK' if result.returncode == 0 else 'FAILED'}")
if result.returncode != 0:
    print(f"(generated sources: {sources})")
sys.exit(result.returncode)
